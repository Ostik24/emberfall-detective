"""Write docs/RESULTS.md: every component's metrics on dev and test, from saved result files.

    uv run python -m evals.write_results

Generated, never edited by hand, so the report cannot drift from the results.
"""

from datetime import date

import pandas as pd

from concierge.config import REPO_ROOT
from evals import report

OUT = REPO_ROOT / "docs" / "RESULTS.md"
SECTIONS = [
    ("C0 normalize (language id)", "c0", ["default"]),
    ("C1 agent: first move and search arguments", "c1", ["default"]),
    ("C3 clarifier with the user simulator", "c3", ["default"]),
    ("C4/C5 search_catalog + rerank (each row changes one factor vs `parent`)", "c4",
     report.C4_CHAIN),
    ("C6 find_title", "c6", ["wratio", "default", "catalog_only", "tmdb_always", "accept80"]),
    ("C7 similar_to (silver labels: TMDB recommendations)", "c7",
     ["e3_docwiki", "gte_docwiki", "stored_doc"]),
    ("C8 get_title_details vs Wikidata", "c8", ["default"]),
    ("C9 watchlist (scripted multi-turn scenarios)", "c9", ["default"]),
    ("C10 external_lookup (out-of-catalog answers, description only)", "c10", ["web"]),
    ("C11 hypothesis verifier (injected false memories)", "c11", ["default"]),
    ("C12 explanations (LLM judge)", "c12", ["default"]),
    ("MCP server over stdio", "mcp", ["stdio"]),
    ("End to end (agent + tools + verifier + explanations)", "e2e", ["default", "uk"]),
]  # fmt: skip


def markdown(frame: pd.DataFrame) -> str:
    """A pipe table (no extra dependency)."""
    if frame.empty:
        return "_no result file yet_\n"
    frame = frame.reset_index()
    cells = [[str(v) for v in row] for row in frame.astype(object).fillna("").values]
    header = "| " + " | ".join(map(str, frame.columns)) + " |"
    rule = "|" + "---|" * len(frame.columns)
    return "\n".join([header, rule, *("| " + " | ".join(r) + " |" for r in cells)]) + "\n"


def main() -> None:
    parts = [
        "# Results\n",
        f"Generated by `evals/write_results.py` on {date.today()} from `evals/results/`. "
        "Cells: mean [95% bootstrap CI]. Dev was used for every decision; test was run once.\n",
    ]
    for title, component, configs in SECTIONS:
        parts.append(f"\n## {title}\n")
        for split in ("dev", "test"):
            parts.append(f"\n**{split}**\n\n")
            parts.append(markdown(report.metrics_table(component, split, configs)))
            for config in configs:
                if extra := report.extra(component, split, config):
                    parts.append(f"\n`{config}` extra: `{extra}`\n")
    parts.append("\n## English vs Ukrainian (paired, same queries)\n")
    for split in ("dev", "test"):
        parts.append(f"\n**{split}**\n\n{markdown(report.en_uk_gap(split).round(3))}")
    parts.append("\n## API spend (real calls; cache replays are free)\n\n")
    spend = report.spend()
    parts.append(markdown(spend.round(3)))
    parts.append(f"\nTotal: ${spend.cost_usd.sum():.2f} over {int(spend.calls.sum())} calls.\n")
    OUT.write_text("".join(parts))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
